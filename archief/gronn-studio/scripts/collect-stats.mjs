#!/usr/bin/env node
// Measures this repository and writes src/lib/project-stats.ts.
//
// Why a generator and not a typed-in list: /stack reads versions from
// package.json at build time so the page cannot lie about what is
// installed. The same rule has to hold for the numbers under the
// timeline — a hand-written "62 commits" is wrong the next time anyone
// commits, and a history page that gets its own figures wrong has
// spent the only thing it has.
//
// It does NOT run during the build. Vercel clones shallow, so `git log`
// there sees a fraction of the history and would quietly produce
// smaller numbers. It runs by hand, writes a file with the date it was
// taken, and the page shows that date. A stale-but-dated number is
// honest; an undated one is not.
//
//   npm run stats
//
// Run it after anything that moves these figures, and commit the result.

import { execSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"

const git = (cmd) => execSync(`git ${cmd}`, { encoding: "utf8" }).trim()
const lines = (glob) => {
  const files = git(`ls-files ${glob}`).split("\n").filter(Boolean)
  return files.reduce(
    (n, f) => n + readFileSync(f, "utf8").split("\n").length,
    0
  )
}
const count = (glob) => git(`ls-files ${glob}`).split("\n").filter(Boolean).length

// ── History ────────────────────────────────────────────────────────
const commits = Number(git("rev-list --count HEAD"))
const dates = git("log --format=%ad --date=short").split("\n")
const firstCommit = dates[dates.length - 1]
const lastCommit = dates[0]
const activeDays = new Set(dates).size

// Squash merges carry "(#123)"; that is how this repo lands a PR.
const mergedPrs = new Set(
  git("log --format=%s")
    .split("\n")
    .map((s) => s.match(/\(#(\d+)\)$/)?.[1])
    .filter(Boolean)
).size

// ── Churn ──────────────────────────────────────────────────────────
let insertions = 0
let deletions = 0
for (const line of git('log --shortstat --format=""').split("\n")) {
  const ins = line.match(/(\d+) insertion/)
  const del = line.match(/(\d+) deletion/)
  if (ins) insertions += Number(ins[1])
  if (del) deletions += Number(del[1])
}

// ── What is here now ───────────────────────────────────────────────
const tsx = lines("'src/**/*.tsx' 'src/*.tsx'")
const ts = lines("'src/**/*.ts' 'src/*.ts'")
const css = lines("'*.css' 'src/**/*.css'")
const tests = lines("'tests/**/*.ts'")
const docs = lines("'*.md' 'docs/**/*.md' 'TIMEVAULT/**/*.md'")

const sourceFiles = count("'src/**/*.ts' 'src/*.ts' 'src/**/*.tsx' 'src/*.tsx'")
const components = count("'src/components/**/*.tsx'")
const routes = count("'src/app/**/page.tsx'")

// ── Things the site itself counts ──────────────────────────────────
const pkg = JSON.parse(readFileSync("package.json", "utf8"))
const dependencies =
  Object.keys(pkg.dependencies ?? {}).length +
  Object.keys(pkg.devDependencies ?? {}).length

const content = JSON.parse(readFileSync("content/site-content.json", "utf8"))
const services = content.services.length

// Palettes, steps and reversals are NOT counted here. They already have
// exports that compute them from the real arrays — ALL_THEME_NAMES and
// STEP_COUNT — and the panel reads those directly. A regex over the
// source was the wrong tool and proved it immediately: it found three
// palettes where there are ten, and a hundred and nine steps where
// there are ninety-six, by matching the events' own date fields.

const e2e = count("'tests/e2e/*.spec.ts'")
const e2eCases = git("ls-files 'tests/e2e/*.spec.ts'")
  .split("\n")
  .filter(Boolean)
  .reduce(
    (n, f) => n + (readFileSync(f, "utf8").match(/^\s*test\(/gm) ?? []).length,
    0
  )

const contrastPairs = Number(
  execSync("node scripts/check-contrast.mjs", { encoding: "utf8" }).match(
    /(\d+) pairs/
  )?.[1] ?? 0
)

const stats = {
  collectedAt: new Date().toISOString().slice(0, 10),
  firstCommit,
  lastCommit,
  commits,
  mergedPrs,
  activeDays,
  insertions,
  deletions,
  tsx,
  ts,
  css,
  tests,
  docs,
  sourceFiles,
  components,
  routes,
  dependencies,
  services,
  e2e,
  e2eCases,
  contrastPairs,
}

const out = `// GENERATED by scripts/collect-stats.mjs — do not edit by hand.
//
// Measured on ${stats.collectedAt}. Regenerate with \`npm run stats\`
// and commit the result; the page shows the date above, because a
// stale-but-dated number is honest and an undated one is not.
//
// This is not generated during the build on purpose: Vercel clones
// shallow, so \`git log\` there would see a fraction of the history and
// report smaller numbers with total confidence.

export type ProjectStats = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(stats).map(([k, v]) => [k, typeof v === "number" ? "number" : "string"])
  ),
  null,
  2
)
  .replace(/"number"/g, "number")
  .replace(/"string"/g, "string")}

export const PROJECT_STATS: ProjectStats = ${JSON.stringify(stats, null, 2)}
`

writeFileSync("src/lib/project-stats.ts", out)
console.log(`Wrote src/lib/project-stats.ts (${stats.collectedAt})`)
for (const [k, v] of Object.entries(stats)) console.log(`  ${k}: ${v}`)
